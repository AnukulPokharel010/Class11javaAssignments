//21.	Write a Java program to demonstrate left-shift and right-shift operators.

public class program21{
  public static void main(String[] args) {

    System.out.println("8>>2="+(8>>2));     //8>>2=8/2^2=2
    System.out.println("32>>3="+(32>>3));   //32>>3 = 32/ 2^3 =4
    System.out.println("64>>4="+(64>>4));   //  64>>4 = 64/ 2^4= 4
    System.out.println("2<<2="+(2<<2));   //  2<<2 = 2*2^2 = 8
    System.out.println("2<<3="+(2<<3));   //   2<<3 = 2*2^3= 16
    System.out.println("6<<4="+(6<<4));   //   6<<4 = 6*2^4= 96
    
  }
  
}